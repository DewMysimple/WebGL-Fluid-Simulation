export type Locale = 'zh' | 'en'
export function detectLocale(
  saved: string | null,
  languages: readonly string[],
): Locale {
  if (saved === 'zh' || saved === 'en') return saved
  return languages[0]?.toLowerCase().startsWith('zh') ? 'zh' : 'en'
}
